"""Offline source-controlled ChatGPT Instructions maintenance (Python 3.11+, Git)."""
import argparse
import difflib
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import tomllib

TEMPLATE = Path(__file__).resolve().with_name("base.md")
INDEX = "vibevm/vibespecs/boot/INDEX.md"
STATIC = "vibevm/vibespecs/boot/STATIC.md"
PERMISSIONS = {"discussion", "assessment", "orchestration", "authorized-publication",
               "authorized-integration", "authorized-continuation"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def safe_path(value):
    require(isinstance(value, str) and value and "\\" not in value
            and not value.startswith("-") and ":" not in value
            and not PurePosixPath(value).is_absolute()
            and all(part not in ("", ".", "..") for part in value.split("/")),
            "Expected repository-relative source path")
    return value


class Snapshot:
    def __init__(self, repository, revision):
        require(re.fullmatch(r"[0-9a-f]{40}", revision), "Use an exact 40-character SHA")
        self.repository, self.revision = repository, revision
        require(self.git("rev-parse", revision + "^{commit}").decode().strip() == revision,
                "Revision must name that exact commit")
        self.files = {}
        for row in self.git("ls-tree", "-rz", revision).split(b"\0"):
            if row:
                metadata, name = row.split(b"\t", 1)
                mode, kind, oid = metadata.decode().split()
                self.files[name.decode()] = (mode, kind, oid)

    def git(self, *args):
        result = subprocess.run(["git", "-C", str(self.repository), *args],
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        require(result.returncode == 0, "Required Git object/operation unavailable: " + args[0])
        return result.stdout

    def read(self, path):
        safe_path(path)
        require(path in self.files, "Missing accepted source: " + path)
        mode, kind, oid = self.files[path]
        require(mode in ("100644", "100755") and kind == "blob",
                "Source must be an ordinary committed file: " + path)
        return self.git("cat-file", "blob", oid)


def native_inventory(source):
    """Consume generated INDEX and native slot receipts, never resolve dependencies."""
    require(INDEX in source.files and "vibe.lock" in source.files,
            "Native binding needs accepted INDEX and lock")
    index = tomllib.loads(source.read(INDEX).decode())
    require(index.get("schema") == 1, "Unsupported native INDEX schema")
    entries = index.get("entry", [])
    require(isinstance(entries, list), "Invalid INDEX entries")
    for entry in entries:
        require(entry.get("kind") in ("static", "dynamic"), "Unsupported INDEX kind")
        source.read(entry["path"])
        require("when" not in entry or isinstance(entry["when"], str), "Invalid condition")
    lock = tomllib.loads(source.read("vibe.lock").decode())
    # Verify the materializer's own receipts, not package ranges or dependency edges.
    slots = {}
    require(lock.get("meta", {}).get("schema_version") == 7, "Unsupported native lock schema")
    for package in lock.get("package", []):
        slot = ("vibevm/vibedeps/" + package["group"] + "." + package["name"]
                + "/" + package["version"] + "/")
        receipt = tomllib.loads(source.read(slot + ".vibe-slot.toml").decode())
        require(receipt.get("schema") == 1, "Unsupported native slot receipt")
        require(receipt["source_hash"] == package["content_hash"], "Lock/slot identity mismatch")
        slots[slot] = set()
        for item in receipt.get("file", []):
            path = slot + safe_path(item["path"])
            require(digest(source.read(path)) == item["sha256"],
                    "Materialized file differs from native receipt")
            slots[slot].add(path)
    for entry in entries:
        if entry["path"].startswith("vibevm/vibedeps/"):
            slot = next((slot for slot in slots if entry["path"].startswith(slot)), None)
            require(slot is not None,
                    "INDEX route is not bound by the native lock")
            require(entry["path"] in slots[slot],
                    "INDEX route is not declared by its native slot receipt")
    paths = {INDEX, "vibe.lock"}
    paths.update(entry["path"] for entry in entries)
    paths.update(path for path in source.files if path.startswith("vibevm/vibedeps/"))
    if STATIC in source.files:
        paths.add(STATIC)
    return paths, entries



GENERATOR = "shared-governance/chatgpt"
MARKER = "<!-- Generated by shared-governance/chatgpt; edit custom.md and binding.json, then regenerate. -->\n"


def encoded(value):
    return (json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n").encode()


def ordinary(root, path):
    """Keep local reads/writes inside this project; do not follow links."""
    root, path = root.resolve(), path.absolute()
    require(path.is_relative_to(root) and path.resolve().is_relative_to(root),
            "Local path must stay inside the project")
    for part in (path, *path.parents):
        require(not part.is_symlink() and not getattr(part, "is_junction", lambda: False)(),
                "Local links are unsupported")
        if part == root:
            break
    require(not path.exists() or path.is_file(), "Expected an ordinary local file")
    return path


def validate_binding(binding):
    fields = {"schema", "repository", "navigation_ref", "mode", "role", "permissions",
              "native", "local_sources", "character_budget", "cache_selection", "cache_enabled"}
    require(set(binding) == fields and binding["schema"] == 2, "Unsupported binding schema/fields")
    require(re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", binding["repository"]),
            "Invalid repository identity")
    require(re.fullmatch(r"[A-Za-z0-9_.-]+", binding["navigation_ref"]), "Invalid navigation ref")
    require(binding["mode"] in ("orchestration-review", "read-only-preview"), "Unknown client mode")
    permissions = binding["permissions"]
    require(isinstance(permissions, list) and set(permissions) <= PERMISSIONS, "Unknown capability")
    require(binding["mode"] != "read-only-preview" or set(permissions) <= {"discussion", "assessment"},
            "Read-only preview cannot enable mutations")
    require(binding["native"] in ("materialized", "absent"), "Unknown native route mode")
    require(type(binding["character_budget"]) is int and 0 < binding["character_budget"] <= 8000,
            "Invalid owner-bound character budget")
    require(isinstance(binding["role"], str) and binding["role"].strip(), "Missing client role")
    require(type(binding["cache_enabled"]) is bool, "Cache enablement must be explicit")
    for field in ("local_sources", "cache_selection"):
        require(isinstance(binding[field], list), "Expected path list: " + field)
        require(len(binding[field]) == len(set(binding[field])), "Duplicate selected path")
        for path in binding[field]:
            safe_path(path)
    require(not binding["cache_enabled"] or binding["cache_selection"], "Cache needs explicit selection")


def project(source_repository, binding, custom, accepted_sha, authority_anchor):
    validate_binding(binding)
    require(authority_anchor.startswith("https://github.com/" + binding["repository"] + "/"),
            "Authority anchor must belong to the bound project")
    source = Snapshot(source_repository, accepted_sha)
    source.read("AGENTS.md")
    paths, entries = {"AGENTS.md"}, []
    if binding["native"] == "materialized":
        native, entries = native_inventory(source)
        paths.update(native)
    else:
        require(INDEX not in source.files and "vibe.lock" not in source.files,
                "Native state exists; cannot declare it absent")
    paths.update(binding["local_sources"])
    if binding["cache_enabled"]:
        paths.update(binding["cache_selection"])
    inputs = {path: digest(source.read(path)) for path in sorted(paths)}
    template = TEMPLATE.read_text(encoding="utf-8")
    require(template.count("{{BINDING}}") == template.count("{{CUSTOM}}") == 1,
            "Expected one binding and one custom template marker")
    navigation = f'https://github.com/{binding["repository"]}/blob/{binding["navigation_ref"]}/AGENTS.md'
    block = (f'Repository: `{binding["repository"]}`. Client mode: {binding["mode"]}.\n'
             f'Role: {binding["role"]}\n\n'
             f'[Project source navigation]({navigation}) is a discovery link, never an acceptance pin.\n'
             f'Capabilities, only where separately authorized: {", ".join(binding["permissions"])}.\n'
             'Additional local/product entry paths (read at the independently frozen accepted revision): '
             + (", ".join('`' + path + '`' for path in binding["local_sources"]) or "AGENTS discovery") + ".")
    require(custom.strip(), "Custom Markdown must not be empty")
    text = MARKER + template.replace("{{BINDING}}", block).replace("{{CUSTOM}}", custom.rstrip())
    require("{{" not in text and "}}" not in text, "Unresolved template markers")
    require(len(text) < binding["character_budget"], "Full Instructions exceed budget; never truncate")
    artifacts = {"instructions.md": text.encode()}
    if binding["cache_enabled"]:
        base = f'https://github.com/{binding["repository"]}/blob/{accepted_sha}/'
        manifest = {"schema": 2, "kind": "optional-source-cache", "repository": binding["repository"],
                    "accepted_sha": accepted_sha, "authority_anchor": authority_anchor,
                    "files": {path: inputs[path] for path in binding["cache_selection"]},
                    "limitations": "snapshot only; upload/addressability/freshness/activation unverified"}
        artifacts["sources-manifest.json"] = encoded(manifest)
        parts = [MARKER, "# Optional source cache\n\nSnapshot, not authority.\n"]
        for path in binding["cache_selection"]:
            parts.append(f'\n## {path}\n\nSource: {base}{path}\n\n' + source.read(path).decode())
        artifacts["sources.md"] = "".join(parts).encode()
    tool_files = {name: digest((TEMPLATE.parent / name).read_bytes()) for name in ("project.py", "base.md")}
    package = tomllib.loads((TEMPLATE.parents[2] / "vibe.toml").read_text(encoding="utf-8"))["package"]
    receipt = {"schema": 2, "generator": GENERATOR, "repository": binding["repository"],
               "accepted_sha": accepted_sha, "authority_anchor": authority_anchor,
               "acceptance_verification": "external owner/review evidence required; consistency only",
               "tool": {"package": package["group"] + "/" + package["name"],
                        "version": package["version"], "files": tool_files},
               "binding_sha256": digest(encoded(binding)), "custom_sha256": digest(custom.encode()),
               "unicode_characters": len(text), "source_files": inputs, "native_entries": entries,
               "condition_disposition": "preserved, not evaluated or adopted by projector",
               "artifacts": {name: digest(data) for name, data in artifacts.items()}}
    return artifacts, receipt


def difference(before, after, label):
    return "".join(difflib.unified_diff(before.decode().splitlines(keepends=True),
                                      after.decode().splitlines(keepends=True),
                                      fromfile="previous/" + label, tofile="desired/" + label))


def maintain(root, binding_path, source_repository, accepted_sha, authority_anchor, update=False):
    root = root.resolve()
    binding_path = ordinary(root, binding_path)
    directory = binding_path.parent
    custom_path = ordinary(root, directory / "custom.md")
    custom = custom_path.read_text(encoding="utf-8")
    binding = json.loads(binding_path.read_text(encoding="utf-8"))
    artifacts, receipt = project(source_repository, binding, custom, accepted_sha, authority_anchor)
    receipt_path = ordinary(root, directory / "receipt.json")
    previous = json.loads(receipt_path.read_text(encoding="utf-8")) if receipt_path.exists() else None
    owned = {}
    if previous is not None:
        require(previous.get("schema") == 2 and previous.get("generator") == GENERATOR
                and previous.get("repository") == binding["repository"], "Unknown or foreign receipt; preserve it")
        owned = previous["artifacts"]
        require(isinstance(owned, dict) and set(owned) <= {"instructions.md", "sources.md", "sources-manifest.json"},
                "Unsupported owned artifact set")
    changes, diffs = [], {}
    # Validate the complete write plan first. Preserve locally modified/unknown output.
    for name in sorted(set(artifacts) | set(owned)):
        path = ordinary(root, directory / name)
        actual = path.read_bytes() if path.exists() else b""
        desired = artifacts.get(name, b"")
        if path.exists() and update:
            require(name in owned and digest(actual) == owned[name],
                    "Unknown or locally modified generated file; preserve/reconcile: " + name)
        if actual != desired or (name in artifacts and not path.exists()):
            changes.append(name)
            diffs[name] = difference(actual, desired, name)
    evidence_changed = not receipt_path.exists() or receipt_path.read_bytes() != encoded(receipt)
    before, after = previous["source_files"] if previous else {}, receipt["source_files"]
    status = {"schema": 2, "effective_content": "CHANGED" if changes else "NO_OP",
              "instructions": "CHANGED" if "instructions.md" in changes else "NO_OP",
              "sources": ("CHANGED" if any(name.startswith("sources") for name in changes) else
                          "NO_OP" if binding["cache_enabled"] else "DISABLED"),
              "maintenance_evidence": "CHANGED" if evidence_changed else "NO_OP",
              "source_changes": [path for path in sorted(before.keys() | after.keys())
                                 if before.get(path) != after.get(path)],
              "diffs": diffs, "live_settings_verified": False,
              "application": "owner reviews/applies/readbacks; preserve unknown live rules"}
    if update:
        for name in changes:
            path = directory / name
            if name in artifacts:
                path.write_bytes(artifacts[name])
            elif path.exists():
                path.unlink()  # Only verified previously owned generated cache files.
        if evidence_changed:
            receipt_path.write_bytes(encoded(receipt))
    return status, bool(changes or evidence_changed)


def compare_live(generated, exported, export_format):
    before = exported.read_bytes().decode("utf-8")
    if export_format == "fenced":
        require(before.startswith("```markdown\n") and before.endswith("```\n")
                and before.count("```") == 2, "Expected one complete markdown fence")
        before = before[len("```markdown\n"):-len("```\n")]
    after = generated.read_bytes()
    return {"comparison": "NO_OP" if before.encode() == after else "CHANGED",
            "live_settings_verified": False, "baseline_provenance": "owner-supplied export; UI unverified",
            "diff": difference(before.encode(), after, "instructions.md"),
            "application": "preserve/reconcile unknown live rules before manual replacement"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("check", "update", "compare"))
    parser.add_argument("--repository", type=Path, required=True)
    parser.add_argument("--binding", type=Path, required=True)
    parser.add_argument("--source-repository", type=Path, help="Optional separate read-only Git object store")
    parser.add_argument("--accepted-sha", help="Independently verified exact authority, never inferred")
    parser.add_argument("--authority-anchor", help="Current owner/review evidence, receipt only")
    parser.add_argument("--live-export", type=Path)
    parser.add_argument("--live-format", choices=("raw", "fenced"), default="raw")
    args = parser.parse_args()
    try:
        root = args.repository.resolve()
        binding = args.binding if args.binding.is_absolute() else root / args.binding
        if args.action == "compare":
            require(args.live_export is not None, "Compare needs an explicit owner export")
            generated = ordinary(root, binding.parent / "instructions.md")
            status = compare_live(generated, args.live_export, args.live_format)
            stale = False
        else:
            require(args.live_export is None, "Live export is only for read-only comparison")
            require(args.accepted_sha and args.authority_anchor, "Supply independent accepted SHA/authority")
            status, stale = maintain(root, binding, args.source_repository or root,
                                     args.accepted_sha, args.authority_anchor, args.action == "update")
        print(json.dumps(status, indent=2, ensure_ascii=False))
        return 1 if args.action == "check" and stale else 0
    except (ValueError, KeyError, TypeError, AttributeError, OSError) as error:
        parser.exit(2, "Projection refused: " + str(error) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
